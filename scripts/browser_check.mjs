import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const reportDir=process.env.AUTHENFY_REPORT_DIR || 'reports';
await fs.mkdir(reportDir,{recursive:true});
const browser = await chromium.launch({headless:true, channel:'chrome'});
try {
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror', error=>errors.push(String(error)));
await page.goto(process.env.AUTHENFY_URL || 'http://127.0.0.1:5000');
await page.getByText('Analyzer ready',{exact:true}).waitFor();
const health=await (await page.request.get(new URL('/health',page.url()).href)).json();
if (process.env.AUTHENFY_EXPECT_ENGINE) assert.equal(health.engine,process.env.AUTHENFY_EXPECT_ENGINE);
await page.screenshot({path:path.join(reportDir,'desktop.png'),fullPage:true});
await page.locator('#fileInput').setInputFiles('tests/fixtures/gray.png');
await page.getByRole('button',{name:'Analyze media'}).click();
await page.locator('#result:not([hidden])').waitFor({timeout:120000});
assert.ok(['Inconclusive','Synthetic signals detected','Low synthetic signals'].includes(await page.locator('#verdict').textContent()));
assert.equal(await page.locator('#frames tr').count(),1);
const receiptId=await page.locator('#receiptId').inputValue();
assert.match(receiptId,/^[a-f0-9]{32}$/);
const receiptResponse=await page.request.get(new URL(`/receipts/${receiptId}`,page.url()).href);
assert.equal(receiptResponse.status(),200);
const receipt=await receiptResponse.json();
assert.equal(receipt.model.sha256,health.model.sha256);
assert.equal(receipt.review_required,true);
await page.locator('#verifyFile').setInputFiles('tests/fixtures/gray.png');
await page.getByRole('button',{name:'Verify exact file'}).click();
await page.getByText(/Exact file match. The local receipt/).waitFor();
await page.screenshot({path:path.join(reportDir,'desktop-result.png'),fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:path.join(reportDir,'mobile.png'),fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.deepEqual(errors,[]);
const before=await page.locator('#fileLabel').textContent();
await page.locator('#fileInput').setInputFiles({name:'<img src=x onerror=alert(1)>.png',mimeType:'image/png',buffer:await fs.readFile('tests/fixtures/gray.png')});
assert.notEqual(await page.locator('#fileLabel').textContent(),before);
assert.equal(await page.locator('#fileLabel img').count(),0);
await page.locator('#fileInput').setInputFiles({name:'broken.png',mimeType:'image/png',buffer:Buffer.from('invalid')});
await page.getByRole('button',{name:'Analyze media'}).click();
await page.locator('#error:not([hidden])').waitFor();
assert.match(await page.locator('#error').textContent(),/corrupt/);
assert.equal(await page.locator('#result').isVisible(),false);
const report={status:'passed',purpose:process.env.AUTHENFY_VALIDATION_PURPOSE || 'Installed-model application regression',engine:health.engine,model:health.model,flows:['image inference','receipt download and model identity','exact-file verification','mobile layout','filename injection defense','decode error recovery'],browserErrors:errors};
await fs.writeFile(path.join(reportDir,'browser-validation.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report));
} finally { await browser.close(); }
